// ── Legacy named exports (for storefront components) ─────────────────────────

export const categories = initialCategories;
export const products = initialProducts;

export function getProductBySlug(slug: string) {
  return initialProducts.find((p) => p.slug === slug);
}

export function getProductsByCategory(slug: string) {
  if (slug === "all") return initialProducts;
  return initialProducts.filter((p) => p.category === slug);
}

export function getRelatedProducts(product: AdminProduct, count = 4) {
  return initialProducts.filter((p) => p.id !== product.id).slice(0, count);
}

export function getBestSellers(count = 4) {
  return [...initialProducts].sort((a, b) => b.reviewCount - a.reviewCount).slice(0, count);
}

export function getCategoryBySlug(slug: string) {
  return initialCategories.find((c) => c.slug === slug);
}
